def list_files(path):
    datapath = []
    for root, _, files in os.walk(path):
        for file in files:
            if file.endswith(".ckpt"):
                datapath.append(os.path.join(root, file))
    return sorted(datapath)


def _sample_lengths(path):
    data = torch.load(path, map_location="cpu", weights_only=False)
    loss_mask = data["loss_mask"].float()
    answer_positions = torch.nonzero(loss_mask > 0, as_tuple=False).flatten()
    answer_tokens = int(answer_positions.numel())
    context_len = int(answer_positions[0].item()) if answer_tokens > 0 else -1
    return context_len, answer_tokens


def filter_by_sample_metadata(
    files,
    min_mask_tokens=0,
    min_context_len=None,
    max_context_len=None,
    cache_path=None,
):
    """Keep files matching reply/context filters. Caches the result."""
    if min_mask_tokens <= 0 and min_context_len is None and max_context_len is None:
        return files

    if cache_path and os.path.exists(cache_path):
        with open(cache_path, "r") as f:
            cached = json.load(f)
        cache_matches = (
            cached.get("min_mask_tokens") == min_mask_tokens
            and cached.get("min_context_len") == min_context_len
            and cached.get("max_context_len") == max_context_len
            and set(cached.get("source_files", [])) == set(files)
        )
        if cache_matches:
            print(f"[filter] loaded {len(cached['kept_files'])} files from cache {cache_path}")
            return cached["kept_files"]

    kept = []
    print(
        f"[filter] scanning {len(files)} ckpts "
        f"(min_mask_tokens > {min_mask_tokens}, "
        f"min_context_len={min_context_len}, max_context_len={max_context_len})..."
    )
    for i, f in enumerate(files):
        try:
            context_len, answer_tokens = _sample_lengths(f)
        except Exception as e:
            print(f"  [skip] {f}: {e}")
            continue
        if answer_tokens <= min_mask_tokens:
            continue
        if min_context_len is not None and context_len < min_context_len:
            continue
        if max_context_len is not None and context_len > max_context_len:
            continue
        kept.append(f)
        if (i + 1) % 500 == 0:
            print(f"  scanned {i+1}/{len(files)}, kept {len(kept)}")
    print(f"[filter] kept {len(kept)}/{len(files)} ({100*len(kept)/max(len(files),1):.1f}%)")

    if cache_path:
        os.makedirs(os.path.dirname(cache_path) or ".", exist_ok=True)
        with open(cache_path, "w") as f:
            json.dump(
                {
                    "min_mask_tokens": min_mask_tokens,
                    "min_context_len": min_context_len,
                    "max_context_len": max_context_len,
                    "source_files": files,
                    "kept_files": kept,
                },
                f,
            )
        print(f"[filter] cached to {cache_path}")
    return kept


class AdapterDataset(Dataset):
    def __init__(self, datapath, exit_layer):
        self.data = datapath
        self.exit_layer = exit_layer

    def __len__(self):
        return len(self.data)

    def __getitem__(self, index):
        data = torch.load(self.data[index], map_location="cpu", weights_only=False)

        hidden_state = data["hidden_state"][None, :]
        loss_mask = data["loss_mask"]
        hidden_state_early = data[f"hidden_state_layer{self.exit_layer}"][None, :]

        orig_len = loss_mask.shape[0]
        loss_mask_shifted = torch.zeros(orig_len, dtype=torch.float32)
        if orig_len > 1:
            loss_mask_shifted[:orig_len - 1] = loss_mask[1:orig_len].float()

        # GT labels for direct-supervision CE: hidden_state at position i predicts
        # the token at position i+1, so the label at position i is input_ids[i+1].
        # Shift left by one to stay aligned with loss_mask_shifted; the trailing
        # slot is -100 (ignored by F.cross_entropy and never selected because
        # loss_mask is 0 there). Only used when --ce_target gt.
        input_ids = data.get("input_ids")
        if input_ids is not None:
            gt_labels = torch.full((orig_len,), -100, dtype=torch.long)
            if orig_len > 1:
                gt_labels[:orig_len - 1] = input_ids[1:orig_len].long()
            gt_labels = gt_labels.tolist()
        else:
            gt_labels = None

        length = hidden_state.shape[1]
        attention_mask = [1] * length

        # 3D mRoPE position_ids if saved (shape: (3, seq_len)). If absent,
        # adapter falls back to 1D arange (text-style T=H=W).
        position_ids = data.get("position_ids", None)
        if position_ids is not None:
            position_ids = position_ids[:, None, :]  # (3, 1, seq_len) — pseudo-batch dim

        return {
            "attention_mask": attention_mask,
            "loss_mask": loss_mask_shifted.tolist(),
            "gt_labels": gt_labels,
            "target": hidden_state,
            "hidden_state_big": hidden_state,
            "hidden_state_early": hidden_state_early,
            "position_ids": position_ids,
        }


class DataCollatorWithPadding:
    @staticmethod
    def paddingtensor(intensors, target_len):
        batch, cur_len, hidden = intensors.shape
        padding_tensor = torch.zeros(batch, target_len - cur_len, hidden, dtype=intensors.dtype)
        return torch.cat((intensors, padding_tensor), dim=1)

    @staticmethod
    def padding_position_ids(intensors, target_len):
        # intensors: (3, 1, seq_len)
        cur_len = intensors.shape[2]
        if cur_len >= target_len:
            return intensors
        padding = torch.zeros(3, 1, target_len - cur_len, dtype=intensors.dtype)
        return torch.cat((intensors, padding), dim=2)

    def __call__(self, features: List[Dict[str, Any]]) -> Dict[str, Any]:
        max_length = max(item["hidden_state_big"].shape[1] for item in features)
        out = {
            "hidden_states": torch.cat([self.paddingtensor(item["hidden_state_big"], max_length) for item in features]),
            "hidden_states_early": torch.cat([self.paddingtensor(item["hidden_state_early"], max_length) for item in features]),
            "target": torch.cat([self.paddingtensor(item["target"], max_length) for item in features]),
            "loss_mask": torch.tensor([item["loss_mask"] + [0] * (max_length - len(item["loss_mask"])) for item in features]),
            "attention_mask": torch.tensor([item["attention_mask"] + [0] * (max_length - len(item["attention_mask"])) for item in features]),
        }
        # Stack GT labels (-100 padded) if every sample carries them.
        if all(item.get("gt_labels") is not None for item in features):
            out["gt_labels"] = torch.tensor(
                [item["gt_labels"] + [-100] * (max_length - len(item["gt_labels"])) for item in features],
                dtype=torch.long,
            )
        else:
            out["gt_labels"] = None
        # Stack 3D position_ids if all features have them; else None.
        if all(f.get("position_ids") is not None for f in features):
            pos_padded = [self.padding_position_ids(f["position_ids"], max_length) for f in features]
            # Each is (3, 1, max_length); cat along batch dim → (3, B, max_length).
            out["position_ids"] = torch.cat(pos_padded, dim=1)
        else:
            out["position_ids"] = None
        return out


